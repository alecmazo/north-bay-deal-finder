export function getProperty(id: string) {
  return PROPERTIES.find((p) => p.id === id);
}

export function equityGap(p: Property) {
  return p.baseArv - p.listPrice;
}

export function priceDropPct(p: Property) {
  if (!p.originalPrice) return 0;
  return ((p.listPrice - p.originalPrice) / p.originalPrice) * 100;
}
